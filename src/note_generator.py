import json
import sys
from pathlib import Path

from gemini_client import create_gemini_client, get_model_name


NOTE_GENERATION_PROMPT = """
You are the study-note generation engine for LectureLens.

You will receive structured multimodal analysis of an educational YouTube
video. The analysis contains:

- spoken lecture content
- timestamps
- visual content
- visible text
- relationships between speech and visuals
- key concepts

Convert this analysis into high-quality study notes.

GOALS:

1. Make the notes useful for a student revising the lecture.
2. Preserve important technical information accurately.
3. Organize the lecture into meaningful sections.
4. Combine spoken explanations with relevant visual information.
5. Do not merely repeat the input JSON.
6. Remove greetings, filler, advertisements and promotional material.
7. Do not invent information that is not supported by the input.

For every meaningful section include:

- Section title
- Timestamp
- Clear explanation
- Important concepts
- Important examples
- Visual explanation when a meaningful visual exists
- Important visible text when useful
- Key takeaway

VISUAL CONTENT:

If the analysis contains a diagram, chart, table, code,
formula, screenshot or slide, explicitly incorporate it into the notes.

For diagrams:
- explain the components
- explain the relationships between them
- explain how the visual supports the lecture

For charts:
- explain axes, trends and important values when available

For tables:
- preserve important rows/columns and explain their significance

For formulas:
- preserve the formula accurately and explain its meaning

For code:
- preserve important code concepts
- explain what the code does

For screenshots/slides:
- explain the educational information shown
- preserve important readable text

Do not claim that an actual image is present unless the input provides
visual information about it.

OUTPUT FORMAT:

Return ONLY valid JSON.

{
  "title": "...",
  "overview": "...",
  "duration_seconds": 0,
  "sections": [
    {
      "section_number": 1,
      "title": "...",
      "start_time": 0,
      "end_time": 60,
      "explanation": "...",
      "key_concepts": [
        "..."
      ],
      "examples": [
        "..."
      ],
      "visual_explanation": "...",
      "important_visual_text": [
        "..."
      ],
      "key_takeaway": "..."
    }
  ],
  "final_takeaways": [
    "..."
  ]
}

QUALITY REQUIREMENTS:

- Keep the chronological structure of the lecture.
- Merge closely related sections when appropriate.
- Avoid unnecessary repetition.
- Keep timestamps accurate to the supplied analysis.
- Preserve technical terminology.
- Prefer clear educational explanations over transcript-like writing.
- If a section has no meaningful visual content, use null for
  visual_explanation and [] for important_visual_text.
"""


def load_json(input_path):
    """Load a JSON file."""

    input_path = Path(input_path)

    if not input_path.exists():
        raise FileNotFoundError(
            f"File not found: {input_path}"
        )

    with open(
        input_path,
        "r",
        encoding="utf-8"
    ) as f:
        return json.load(f)


def load_analysis(input_path):
    """Load Gemini's multimodal analysis JSON."""

    return load_json(input_path)


def load_visual_manifest(input_path):
    """
    Load the visual manifest generated by visual_extractor.py.

    The manifest contains the actual image paths corresponding to
    the visual elements identified by Gemini.
    """

    input_path = Path(input_path)

    if not input_path.exists():
        print(
            f"Warning: visual manifest not found: {input_path}"
        )
        print(
            "Continuing without attached visual assets."
        )
        return {
            "visual_count": 0,
            "visuals": []
        }

    return load_json(input_path)


def generate_notes(analysis):
    """Generate study notes from multimodal analysis."""

    client = create_gemini_client()
    model = get_model_name()

    analysis_json = json.dumps(
        analysis,
        ensure_ascii=False,
        indent=2
    )

    prompt = f"""
{NOTE_GENERATION_PROMPT}

Here is the multimodal lecture analysis:

{analysis_json}
"""

    print("Generating study notes with Gemini...")
    print(f"Model: {model}")

    response = client.models.generate_content(
        model=model,
        contents=prompt,
    )

    return response.text


def clean_json_response(text):
    """Remove Markdown code fences if Gemini returns them."""

    cleaned = text.strip()

    if cleaned.startswith("```json"):
        cleaned = cleaned[7:]

    elif cleaned.startswith("```"):
        cleaned = cleaned[3:]

    if cleaned.endswith("```"):
        cleaned = cleaned[:-3]

    return cleaned.strip()


def attach_visuals_to_notes(
    notes,
    visual_manifest
):
    """
    Attach actual visual assets from visual_manifest.json to the
    corresponding study-note sections.

    Gemini creates the educational explanation.

    visual_extractor.py provides the actual image files.

    This function connects the two.
    """

    visuals = visual_manifest.get(
        "visuals",
        []
    )

    if not isinstance(visuals, list):
        visuals = []

    sections = notes.get(
        "sections",
        []
    )

    for section in sections:

        section_number = section.get(
            "section_number"
        )

        section_start = section.get(
            "start_time",
            0
        )

        section_end = section.get(
            "end_time",
            0
        )

        section_visuals = []

        for visual in visuals:

            visual_section = visual.get(
                "section_number"
            )

            timestamp = visual.get(
                "timestamp"
            )

            if visual_section != section_number:
                continue

            if timestamp is None:
                continue

            try:
                timestamp = float(timestamp)
                section_start = float(section_start or 0)
                section_end = float(section_end or 0)
            except (TypeError, ValueError):
                continue

            # Normally the section number is enough because the
            # visual manifest came from the same analysis.
            # The timestamp check provides additional protection
            # against accidental mismatches.
            if (
                section_start <= timestamp <= section_end
                or visual_section == section_number
            ):
                section_visuals.append(
                    {
                        "visual_index": visual.get(
                            "visual_index"
                        ),
                        "timestamp": timestamp,
                        "type": visual.get(
                            "type",
                            "other"
                        ),
                        "description": visual.get(
                            "description",
                            ""
                        ),
                        "visible_text": visual.get(
                            "visible_text",
                            ""
                        ),
                        "image": visual.get(
                            "image"
                        ),
                    }
                )

        section["visuals"] = section_visuals

    return notes


def save_notes(
    notes_text,
    output_path,
    visual_manifest=None
):
    """Validate and save generated notes as JSON."""

    output_path = Path(output_path)
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    cleaned = clean_json_response(
        notes_text
    )

    try:
        notes = json.loads(cleaned)

    except json.JSONDecodeError as exc:

        print(
            "Gemini returned invalid JSON."
        )

        print(cleaned)

        raise ValueError(
            "Could not parse generated study notes as JSON."
        ) from exc

    if visual_manifest is not None:
        notes = attach_visuals_to_notes(
            notes,
            visual_manifest
        )

    with open(
        output_path,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            notes,
            f,
            ensure_ascii=False,
            indent=2
        )

    print(
        f"Study notes JSON saved to: "
        f"{output_path}"
    )

    return notes


def format_timestamp(seconds):
    """Convert seconds into MM:SS or HH:MM:SS."""

    seconds = int(seconds or 0)

    hours = seconds // 3600
    minutes = (seconds % 3600) // 60
    secs = seconds % 60

    if hours:
        return (
            f"{hours:02d}:"
            f"{minutes:02d}:"
            f"{secs:02d}"
        )

    return (
        f"{minutes:02d}:"
        f"{secs:02d}"
    )


def make_markdown_image_path(
    image_path,
    markdown_output_path
):
    """
    Convert the stored image path into a path relative to the
    generated Markdown file.
    """

    if not image_path:
        return None

    image_path = Path(image_path)
    markdown_output_path = Path(
        markdown_output_path
    )

    try:
        relative_path = Path(
            __import__("os").path.relpath(
                image_path,
                start=markdown_output_path.parent
            )
        )

        return relative_path.as_posix()

    except ValueError:
        return image_path.as_posix()


def create_markdown(
    notes,
    markdown_output_path
):
    """Convert structured study notes into Markdown."""

    lines = []

    title = notes.get(
        "title",
        "Lecture Notes"
    )

    lines.append(
        f"# {title}"
    )

    lines.append("")

    overview = notes.get(
        "overview"
    )

    if overview:

        lines.append(
            "## Overview"
        )

        lines.append("")

        lines.append(
            overview
        )

        lines.append("")

    duration = notes.get(
        "duration_seconds"
    )

    if duration:

        lines.append(
            f"**Duration:** "
            f"{format_timestamp(duration)}"
        )

        lines.append("")

    sections = notes.get(
        "sections",
        []
    )

    for section in sections:

        number = section.get(
            "section_number",
            ""
        )

        title = section.get(
            "title",
            "Untitled Section"
        )

        start = format_timestamp(
            section.get(
                "start_time",
                0
            )
        )

        end = format_timestamp(
            section.get(
                "end_time",
                0
            )
        )

        lines.append(
            f"## {number}. {title} "
            f"`[{start} - {end}]`"
        )

        lines.append("")

        explanation = section.get(
            "explanation"
        )

        if explanation:

            lines.append(
                "### Explanation"
            )

            lines.append("")

            lines.append(
                explanation
            )

            lines.append("")

        concepts = section.get(
            "key_concepts",
            []
        )

        if concepts:

            lines.append(
                "### Key Concepts"
            )

            lines.append("")

            for concept in concepts:
                lines.append(
                    f"- {concept}"
                )

            lines.append("")

        examples = section.get(
            "examples",
            []
        )

        if examples:

            lines.append(
                "### Examples"
            )

            lines.append("")

            for example in examples:
                lines.append(
                    f"- {example}"
                )

            lines.append("")

        visual = section.get(
            "visual_explanation"
        )

        if visual:

            lines.append(
                "### Visual Explanation"
            )

            lines.append("")

            lines.append(
                visual
            )

            lines.append("")

        visual_text = section.get(
            "important_visual_text",
            []
        )

        if visual_text:

            lines.append(
                "### Important Visual Text"
            )

            lines.append("")

            for text in visual_text:

                lines.append(
                    f"- `{text}`"
                )

            lines.append("")

        # ---------------------------------------------------------
        # ACTUAL VISUAL ASSETS
        # ---------------------------------------------------------

        visuals = section.get(
            "visuals",
            []
        )

        if visuals:

            lines.append(
                "### Visuals"
            )

            lines.append("")

            for visual_item in visuals:

                image_path = visual_item.get(
                    "image"
                )

                visual_type = visual_item.get(
                    "type",
                    "visual"
                )

                timestamp = visual_item.get(
                    "timestamp",
                    0
                )

                description = visual_item.get(
                    "description",
                    ""
                )

                relative_image = (
                    make_markdown_image_path(
                        image_path,
                        markdown_output_path
                    )
                )

                if relative_image:

                    lines.append(
                        f"**{visual_type.title()} "
                        f"at "
                        f"{format_timestamp(timestamp)}**"
                    )

                    lines.append("")

                    lines.append(
                        f"![{visual_type}]"
                        f"({relative_image})"
                    )

                    lines.append("")

                if description:

                    lines.append(
                        f"*{description}*"
                    )

                    lines.append("")

        takeaway = section.get(
            "key_takeaway"
        )

        if takeaway:

            lines.append(
                "### Key Takeaway"
            )

            lines.append("")

            lines.append(
                f"> {takeaway}"
            )

            lines.append("")

    final_takeaways = notes.get(
        "final_takeaways",
        []
    )

    if final_takeaways:

        lines.append(
            "## Final Takeaways"
        )

        lines.append("")

        for takeaway in final_takeaways:

            lines.append(
                f"- {takeaway}"
            )

        lines.append("")

    return "\n".join(lines)


def save_markdown(
    notes,
    output_path
):
    """Save notes as Markdown."""

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    markdown = create_markdown(
        notes,
        output_path
    )

    with open(
        output_path,
        "w",
        encoding="utf-8"
    ) as f:

        f.write(
            markdown
        )

    print(
        f"Study notes Markdown saved to: "
        f"{output_path}"
    )


def generate_notes_from_file(
    input_path,
    json_output="data/notes/study_notes.json",
    markdown_output="data/notes/study_notes.md",
    visual_manifest_path="data/visuals/visual_manifest.json",
):
    """
    Complete note-generation pipeline.

    1. Load video_analysis.json.
    2. Generate educational notes with Gemini.
    3. Load visual_manifest.json.
    4. Attach actual visual image paths to note sections.
    5. Save JSON notes.
    6. Save Markdown notes with embedded images.
    """

    analysis = load_analysis(
        input_path
    )

    visual_manifest = load_visual_manifest(
        visual_manifest_path
    )

    notes_text = generate_notes(
        analysis
    )

    notes = save_notes(
        notes_text,
        json_output,
        visual_manifest
    )

    save_markdown(
        notes,
        markdown_output
    )

    return notes


if __name__ == "__main__":

    if len(sys.argv) != 2:

        print(
            "Usage:\n"
            "python src/note_generator.py "
            "<analysis_json>"
        )

        sys.exit(1)

    input_path = sys.argv[1]

    generate_notes_from_file(
        input_path
    )

